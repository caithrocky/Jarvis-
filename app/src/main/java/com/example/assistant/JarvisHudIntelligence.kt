package com.example.assistant

import com.example.data.local.DeviceAppKnowledgeEntity
import com.example.data.local.MemoryFactEntity
import com.example.data.local.ScheduledAutomationEntity
import java.util.Calendar
import java.util.Locale

data class HudSpotlightState(
    val kicker: String,
    val headline: String,
    val subtitle: String = ""
)

data class FuturisticMissionSuggestion(
    val id: String,
    val label: String,
    val badge: String,
    val commandPrompt: String,
    val isScheduleAction: Boolean = false,
    val suggestedHour24: Int = 8,
    val suggestedMinute: Int = 0,
    val repeatDaily: Boolean = false
)

/**
 * Dynamic neural HUD intelligence engine:
 * Replaces static greetings ("How can I help you today?") with real-time awareness of
 * what Sir is asking, what the AI decided, upcoming timed automations, live telemetry,
 * and autogenerated contextual missions.
 */
object JarvisHudIntelligence {

    fun buildSpotlight(
        partialVoiceText: String,
        isListening: Boolean,
        isProcessing: Boolean,
        isSpeaking: Boolean,
        isExecuting: Boolean,
        isMicMuted: Boolean,
        lastUserPrompt: String,
        aiChosenHeadline: String?,
        taskProgressTitle: String,
        pendingConfirmationSummary: String?,
        isOnline: Boolean,
        batteryPercent: Int,
        isCharging: Boolean,
        unreadNotificationCount: Int,
        learnedAppsCount: Int,
        memoriesCount: Int,
        activeAutomations: List<ScheduledAutomationEntity>,
        recentMemories: List<MemoryFactEntity>,
        rotationTick: Int,
        nowMs: Long = System.currentTimeMillis()
    ): HudSpotlightState {
        // 1. Live voice stream directly mirrors what is being spoken right now
        if (partialVoiceText.isNotBlank()) {
            val cleanVoice = partialVoiceText.trim().replaceFirstChar {
                if (it.isLowerCase()) it.titlecase(Locale.US) else it.toString()
            }
            return HudSpotlightState(
                kicker = "VOICE STREAM ACTIVE",
                headline = formatDisplayHeadline(cleanVoice),
                subtitle = "Capturing command..."
            )
        }

        // 2. Pending confirmation / safe word check
        if (!pendingConfirmationSummary.isNullOrBlank()) {
            return HudSpotlightState(
                kicker = "CONFIRMATION REQUIRED",
                headline = formatDisplayHeadline(pendingConfirmationSummary),
                subtitle = "Awaiting Sir's go-ahead"
            )
        }

        // 3. Active thinking / executing stage reflects the live request or step
        if (isExecuting || isProcessing) {
            val activeFocus = aiChosenHeadline?.takeIf { it.isNotBlank() }
                ?: summarizePromptAsHeadline(lastUserPrompt).takeIf { it.isNotBlank() }
                ?: taskProgressTitle.ifBlank { "Executing Protocol" }
            return HudSpotlightState(
                kicker = if (isExecuting) "EXECUTING MISSION" else if (isOnline) "NEURAL PROCESSING" else "OFFLINE CORE ACTIVE",
                headline = formatDisplayHeadline(activeFocus),
                subtitle = lastUserPrompt.take(54)
            )
        }

        // 4. Right after a question/task or while speaking: display what the AI decided / what was asked
        if (isSpeaking || !aiChosenHeadline.isNullOrBlank()) {
            val chosen = aiChosenHeadline?.takeIf { it.isNotBlank() }
                ?: summarizePromptAsHeadline(lastUserPrompt)
            if (chosen.isNotBlank()) {
                return HudSpotlightState(
                    kicker = if (isSpeaking) "JARVIS RESPONDING" else "ACTIVE MISSION FOCUS",
                    headline = formatDisplayHeadline(chosen),
                    subtitle = lastUserPrompt.take(54)
                )
            }
        }

        // 5. Listening state
        if (isListening) {
            return HudSpotlightState(
                kicker = if (isOnline) "NEURAL EAR ARMED" else "OFFLINE VOICE READY",
                headline = "Speak Your\nNext Mission",
                subtitle = "Hands-free command channel open"
            )
        }

        // 6. Muted state
        if (isMicMuted) {
            return HudSpotlightState(
                kicker = "AUDIO PAUSED",
                headline = "Mic Standby.\nTap to Resume",
                subtitle = "Wake listener paused by Sir"
            )
        }

        // 7. Dynamic rotating AI Directives grounded in real device telemetry, schedule & context
        val directives = buildContextualDirectives(
            isOnline = isOnline,
            batteryPercent = batteryPercent,
            isCharging = isCharging,
            unreadNotificationCount = unreadNotificationCount,
            learnedAppsCount = learnedAppsCount,
            memoriesCount = memoriesCount,
            activeAutomations = activeAutomations,
            recentMemories = recentMemories,
            lastUserPrompt = lastUserPrompt,
            nowMs = nowMs
        )
        return directives[Math.floorMod(rotationTick, directives.size)]
    }

    fun buildContextualDirectives(
        isOnline: Boolean,
        batteryPercent: Int,
        isCharging: Boolean,
        unreadNotificationCount: Int,
        learnedAppsCount: Int,
        memoriesCount: Int,
        activeAutomations: List<ScheduledAutomationEntity>,
        recentMemories: List<MemoryFactEntity>,
        lastUserPrompt: String,
        nowMs: Long = System.currentTimeMillis()
    ): List<HudSpotlightState> {
        val list = mutableListOf<HudSpotlightState>()
        val nextTask = activeAutomations.firstOrNull { it.isEnabled }
        if (nextTask != null) {
            val countdown = ScheduledAutomationEngine.formatCountdown(nextTask.triggerAtMs, nowMs)
            val timeStr = ScheduledAutomationEngine.formatScheduleTime(nextTask.triggerAtMs)
            list.add(
                HudSpotlightState(
                    kicker = "$countdown • $timeStr",
                    headline = formatDisplayHeadline(nextTask.title),
                    subtitle = "Queued automation ready"
                )
            )
        }

        if (lastUserPrompt.isNotBlank()) {
            val recap = summarizePromptAsHeadline(lastUserPrompt)
            if (recap.isNotBlank()) {
                list.add(
                    HudSpotlightState(
                        kicker = "LAST DIRECTIVE",
                        headline = formatDisplayHeadline(recap),
                        subtitle = "Say a follow-up or schedule it"
                    )
                )
            }
        }

        val hour = Calendar.getInstance().apply { timeInMillis = nowMs }.get(Calendar.HOUR_OF_DAY)
        val timeDirective = when (hour) {
            in 5..11 -> HudSpotlightState(
                kicker = "SOLAR CYCLE • MORNING",
                headline = "Morning Brief &\nSchedule Armed",
                subtitle = "Say \"Daily briefing\" or set a timed task"
            )
            in 12..16 -> HudSpotlightState(
                kicker = "PEAK OPS • AFTERNOON",
                headline = "Autonomous Core\nStanding By",
                subtitle = "Tap keys, automate apps, or run web intel"
            )
            in 17..20 -> HudSpotlightState(
                kicker = "EVENING PROTOCOL",
                headline = "Evening Summary\nReady on Call",
                subtitle = "Ask for unread alerts or schedule tomorrow"
            )
            else -> HudSpotlightState(
                kicker = "NIGHT WATCH ACTIVE",
                headline = "Sleep Guard &\nVoice Wake Live",
                subtitle = "Always listening even with screen off"
            )
        }
        list.add(timeDirective)

        if (unreadNotificationCount > 0) {
            list.add(
                HudSpotlightState(
                    kicker = "SIGNAL INTERCEPT",
                    headline = "$unreadNotificationCount Unread Alert${if (unreadNotificationCount == 1) "" else "s"}\nReady to Triage",
                    subtitle = "Say \"Check my notifications\""
                )
            )
        }

        if (batteryPercent in 1..100) {
            val powerHeadline = when {
                isCharging -> "Power Charging $batteryPercent%.\nNeural Link Optimal"
                batteryPercent <= 20 -> "Low Reserve $batteryPercent%.\nSave Mode Advised"
                else -> "Power Reserve $batteryPercent%.\nAll Systems Green"
            }
            list.add(
                HudSpotlightState(
                    kicker = if (isOnline) "TELEMETRY • ONLINE NIM" else "TELEMETRY • OFFLINE CORE",
                    headline = powerHeadline,
                    subtitle = "$learnedAppsCount apps indexed • $memoriesCount saved memories"
                )
            )
        }

        val memoryHint = recentMemories.firstOrNull()?.summary?.trim()
        if (!memoryHint.isNullOrBlank()) {
            list.add(
                HudSpotlightState(
                    kicker = "MEMORY VAULT SYNCED",
                    headline = formatDisplayHeadline("Recalling: ${memoryHint.take(28)}"),
                    subtitle = "$memoriesCount active memory thread(s)"
                )
            )
        }

        return list.distinctBy { it.headline }
    }

    /**
     * Autogenerates context-sensitive futuristic suggestions backed by real executable actions or schedules.
     */
    fun buildAutogeneratedSuggestions(
        isOnline: Boolean,
        batteryPercent: Int,
        unreadNotificationCount: Int,
        learnedAppsCount: Int,
        activeAutomations: List<ScheduledAutomationEntity>,
        learnedApps: List<DeviceAppKnowledgeEntity>,
        nowMs: Long = System.currentTimeMillis()
    ): List<FuturisticMissionSuggestion> {
        val suggestions = mutableListOf<FuturisticMissionSuggestion>()
        val hour = Calendar.getInstance().apply { timeInMillis = nowMs }.get(Calendar.HOUR_OF_DAY)

        if (unreadNotificationCount > 0) {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "triage_alerts",
                    label = "Triage $unreadNotificationCount Alert${if (unreadNotificationCount == 1) "" else "s"}",
                    badge = "LIVE",
                    commandPrompt = "Check my notifications"
                )
            )
        }

        val hasMorningBrief = activeAutomations.any {
            it.title.contains("brief", ignoreCase = true) || it.commandPrompt.contains("brief", ignoreCase = true)
        }
        if (!hasMorningBrief) {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "schedule_morning_brief",
                    label = "Daily 07:30 AM Brief",
                    badge = "AUTO",
                    commandPrompt = "Daily briefing",
                    isScheduleAction = true,
                    suggestedHour24 = 7,
                    suggestedMinute = 30,
                    repeatDaily = true
                )
            )
        }

        if (hour >= 21 || hour < 5) {
            val hasNightSleep = activeAutomations.any {
                it.commandPrompt.contains("sleep", ignoreCase = true)
            }
            if (!hasNightSleep) {
                suggestions.add(
                    FuturisticMissionSuggestion(
                        id = "schedule_night_sleep",
                        label = "23:30 Sleep Guard",
                        badge = "SCHEDULE",
                        commandPrompt = "Make the device sleep",
                        isScheduleAction = true,
                        suggestedHour24 = 23,
                        suggestedMinute = 30,
                        repeatDaily = true
                    )
                )
            }
        }

        if (isOnline) {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "daily_briefing_now",
                    label = "Run Neural Briefing",
                    badge = "NOW",
                    commandPrompt = "Daily briefing"
                )
            )
        } else {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "offline_diagnostics",
                    label = "Offline System Scan",
                    badge = "LOCAL",
                    commandPrompt = "Check device status"
                )
            )
        }

        val topApp = learnedApps.maxByOrNull { it.usageCount }?.appName
        if (!topApp.isNullOrBlank() && suggestions.size < 4) {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "top_app_launch",
                    label = "Launch $topApp",
                    badge = "APP",
                    commandPrompt = "Open $topApp"
                )
            )
        } else if (learnedAppsCount == 0 && suggestions.size < 4) {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "study_device",
                    label = "Map Installed Apps",
                    badge = "AI SCAN",
                    commandPrompt = "Study my device"
                )
            )
        }

        if (batteryPercent in 1..25 && suggestions.size < 4) {
            suggestions.add(
                FuturisticMissionSuggestion(
                    id = "battery_settings",
                    label = "Battery Reserve Check",
                    badge = "${batteryPercent}%",
                    commandPrompt = "Open battery settings"
                )
            )
        }

        return suggestions.take(4)
    }

    /**
     * Converts any natural user question/command into a sharp 2–6 word futuristic HUD headline.
     */
    fun summarizePromptAsHeadline(rawPrompt: String): String {
        val clean = rawPrompt.trim()
            .replace(Regex("^(hey\\s+)?jarvis[,\\s]*", RegexOption.IGNORE_CASE), "")
            .trim()
        if (clean.isBlank()) return ""
        val lower = clean.lowercase(Locale.US)

        return when {
            lower.contains("sleep") && (lower.contains("device") || lower.contains("phone") || lower.contains("screen")) ->
                "Engaging Sleep Lock"
            lower.contains("shut down") || lower.contains("shutdown") ->
                "Power-Down Protocol"
            lower.contains("restart") || lower.contains("reboot") ->
                "System Reboot Ready"
            lower.contains("unlock") || lower.contains("open the device") || lower.contains("open device") ->
                "Voice Unlock Protocol"
            lower.contains("notification") || lower.contains("missed call") ->
                "Scanning Live Alerts"
            lower.contains("brief") ->
                "Compiling Daily Brief"
            lower.contains("schedule") || lower.contains("remind me") || lower.contains("automate") ->
                "Queuing Timed Mission"
            lower.startsWith("open ") -> {
                val target = clean.drop(5).split(Regex("\\s+")).take(3).joinToString(" ")
                "Launching ${target.replaceFirstChar { it.titlecase(Locale.US) }}"
            }
            else -> {
                val words = clean
                    .replace(Regex("[?!.]+$"), "")
                    .split(Regex("\\s+"))
                    .filter { it.isNotBlank() }
                val clipped = words.take(6).joinToString(" ")
                val withCase = clipped.replaceFirstChar {
                    if (it.isLowerCase()) it.titlecase(Locale.US) else it.toString()
                }
                if (words.size > 6) "$withCase..." else withCase
            }
        }
    }

    /**
     * Wraps a short headline onto 2 balanced lines for crisp centered display under the Orb.
     */
    fun formatDisplayHeadline(raw: String): String {
        val single = raw.replace(Regex("\\s+"), " ").trim()
        if (single.length <= 18) return single
        val words = single.split(" ")
        if (words.size <= 2) return single.take(36)
        val mid = words.size / 2
        val line1 = words.take(mid).joinToString(" ")
        val line2 = words.drop(mid).joinToString(" ").let {
            if (it.length > 24) it.take(21).trimEnd() + "..." else it
        }
        return "$line1\n$line2"
    }
}
